/**
 * Writes `src/services/speedTest/colos.ts` from Cloudflare's own list of its
 * data centres.
 *
 *   npx tsx scripts/speed-test/gen-colos.ts
 *
 * A generator, run by hand and committed with its output, like gen-oui.ts:
 * it reaches `speed.cloudflare.com/locations` (the speed test's own host,
 * recorded in MAIN_OUTBOUND_HOSTS) once, here, so the app never has to.
 */
import { writeFileSync } from 'node:fs';

const res = await fetch('https://speed.cloudflare.com/locations', {
  headers: { Referer: 'https://speed.cloudflare.com/' },
});
if (!res.ok) { console.error(`locations answered ${res.status}`); process.exit(1); }
const list = (await res.json()) as { iata: string; lat: number; lon: number; cca2: string; city: string }[];
const rows = list
  .filter((c) => /^[A-Z]{3}$/.test(c.iata) && Number.isFinite(c.lat) && Number.isFinite(c.lon))
  .sort((a, b) => a.iata.localeCompare(b.iata))
  // Two decimals is about a kilometre - a data centre's city, which is all a
  // pin on a globe says. The separators never occur in a city name.
  .map((c) => `${c.iata}|${c.lat.toFixed(2)}|${c.lon.toFixed(2)}|${c.cca2}|${c.city.replace(/[|;]/g, ' ')}`);

const out = `/**
 * Cloudflare's data centres: IATA code -> where it is (ADR 0054).
 *
 * GENERATED by \`scripts/speed-test/gen-colos.ts\` from
 * https://speed.cloudflare.com/locations on ${new Date().toISOString().slice(0, 10)} - ${rows.length} entries.
 * Do not edit by hand; run the generator.
 *
 * The speed test's engine uses it when Cloudflare's \`/meta\` did not say
 * where its data centre is, so the globe can place the server from the colo
 * code every response carries - never from a lookup of its own. Imported by
 * the engine's process only, not by the renderer.
 */
const TABLE =
  ${JSON.stringify(rows.join(';'))};

export interface ColoPlace { iata: string; latitude: number; longitude: number; country: string; city: string }

let byCode: Map<string, ColoPlace> | null = null;

/** Where a data centre is, by its IATA code in any case; null when the table does not know it. */
export function coloPlace(code: string | null | undefined): ColoPlace | null {
  if (!code) return null;
  if (byCode === null) {
    byCode = new Map();
    for (const row of TABLE.split(';')) {
      const [iata, lat, lon, country, city] = row.split('|');
      byCode.set(iata, { iata, latitude: Number(lat), longitude: Number(lon), country, city });
    }
  }
  return byCode.get(code.trim().toUpperCase()) ?? null;
}
`;
writeFileSync('src/services/speedTest/colos.ts', out);
console.log(`wrote ${rows.length} data centres, ${out.length} bytes`);
