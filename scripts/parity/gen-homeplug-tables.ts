/**
 * Writes `src/services/dissectors/homeplugNames.ts` from the reference's own
 * value tables.
 *
 *   npx tsx scripts/parity/gen-homeplug-tables.ts
 *
 * HomePlug AV names every management message by type - `CM_SET_KEY.REQ (Set
 * Key Request)` - and a vendor's by its own table: Qualcomm Atheros's, which
 * nearly every powerline adapter sold uses, and ST/IoTecha's. Some 240 names,
 * which is what the Info column prints and nothing a hand-kept list would get
 * right.
 *
 * A generator, not a test: it writes a source file and never exits with a
 * status, which is how `check.ts` knows not to run it. Rerun it after a
 * Wireshark upgrade.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

const TABLES: [string, string][] = [
  ['STANDARD', 'homeplug_av.mmhdr.mmtype'],
  ['QUALCOMM', 'homeplug_av.mmhdr.mmtype.qualcomm'],
  ['ST_IOTECHA', 'homeplug_av.mmhdr.mmtype.st'],
];

let out = `/**
 * HomePlug AV's management message names as the reference writes them.
 * GENERATED by \`scripts/parity/gen-homeplug-tables.ts\` from \`tshark -G
 * values\` - edit that, not this.
 */
`;
for (const [name, field] of TABLES) {
  const entries = new Map<number, string>();
  for (const line of dump) {
    const cols = line.split('\t');
    if (cols[0] !== 'V' || cols[1] !== field) continue;
    const value = Number(cols[2]);
    if (!entries.has(value)) entries.set(value, cols[3].trim());
  }
  if (entries.size === 0) throw new Error(`no values for ${field}`);
  out += `\nexport const ${name}: Readonly<Record<number, string>> = {\n${[...entries]
    .map(([v, n]) => `  0x${v.toString(16).padStart(4, '0')}: ${JSON.stringify(n)},`).join('\n')}\n};\n`;
}
writeFileSync('src/services/dissectors/homeplugNames.ts', out);
console.log(`wrote ${TABLES.length} tables`);
