/**
 * Writes `src/services/dissectors/tlsNames.ts` from the reference's own value
 * tables.
 *
 *   npx tsx scripts/parity/gen-tls-tables.ts
 *
 * Cipher suites, signature algorithms, supported groups and extension types -
 * some 760 names, which the hand-kept lists in `tlsTables.ts` covered a
 * fraction of: a suite or algorithm they did not list read `Unknown` where
 * the reference names it, on every TLS and DTLS hello that offered one.
 *
 * A generator, not a test: it writes a source file, so it has no
 * `process.exit` and `check.ts` does not run it. Rerun it after a Wireshark
 * upgrade.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

const TABLES: [string, string][] = [
  ['CIPHER_SUITES', 'tls.handshake.ciphersuite'],
  ['SIGNATURE_ALGORITHMS', 'tls.handshake.sig_hash_alg'],
  ['GROUPS', 'tls.handshake.extensions_supported_group'],
  ['EXTENSIONS', 'tls.handshake.extension.type'],
];

let out = `/**
 * TLS's names as the reference writes them. GENERATED by
 * \`scripts/parity/gen-tls-tables.ts\` from \`tshark -G values\` - edit that,
 * not this.
 */
`;
for (const [name, field] of TABLES) {
  const entries = new Map<number, string>();
  for (const line of dump) {
    const cols = line.split('\t');
    if (cols[0] !== 'V' || cols[1] !== field) continue;
    const value = Number(cols[2]);
    // GREASE has its own spelling in tlsTables.ts; the table keeps names.
    if (!entries.has(value) && !/GREASE/.test(cols[3])) entries.set(value, cols[3].trim());
  }
  if (entries.size === 0) throw new Error(`no values for ${field}`);
  out += `\nexport const ${name}: Readonly<Record<number, string>> = {\n${[...entries]
    .map(([v, n]) => `  0x${v.toString(16).padStart(4, '0')}: ${JSON.stringify(n)},`).join('\n')}\n};\n`;
}
writeFileSync('src/services/dissectors/tlsNames.ts', out);
console.log(`wrote ${TABLES.length} tables`);
