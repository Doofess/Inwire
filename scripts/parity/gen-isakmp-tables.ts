/**
 * Writes `src/services/dissectors/isakmpTables.ts` from the reference's own
 * value tables.
 *
 *   npx tsx scripts/parity/gen-isakmp-tables.ts
 *
 * ISAKMP's names - payload types, exchange types, notify messages, transform
 * IDs, the IKEv1 attributes - are some four hundred strings, several of them
 * ranges ("Private Use", "RESERVED (Future Use)"), and copying them by hand is
 * how a dissector ends up a letter off from the reference on a row nobody
 * re-reads. `tshark -G values` prints every one. Where IKEv1 and IKEv2 share a
 * field name the dump holds both tables back to back, the second starting
 * over at its lowest value; they are split there.
 *
 * A generator, not a test: it writes a source file and never exits with a
 * status, which is how `check.ts` knows not to run it. Rerun it after a Wireshark
 * upgrade; `scripts/isakmp/dissect.ts` is what notices that it is due.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

type Range = [number, number, string];
const ranges = new Map<string, Range[][]>();
const values = new Map<string, Map<number, string>[]>();
for (const line of dump) {
  const cols = line.split('\t');
  if (cols[0] === 'R' && cols[1].startsWith('isakmp.')) {
    const tables = ranges.get(cols[1]) ?? [[]];
    const current = tables[tables.length - 1];
    const lo = Number(cols[2]);
    // A table starting over is the next version's.
    if (current.length > 0 && lo < current[current.length - 1][0]) tables.push([]);
    tables[tables.length - 1].push([lo, Number(cols[3]), cols[4].trim()]);
    ranges.set(cols[1], tables);
  } else if (cols[0] === 'V' && cols[1].startsWith('isakmp.')) {
    const tables = values.get(cols[1]) ?? [new Map()];
    const value = Number(cols[2]);
    if (tables[tables.length - 1].has(value)) tables.push(new Map());
    tables[tables.length - 1].set(value, cols[3].trim());
    values.set(cols[1], tables);
  }
}

/** [export name, field, which table (0 = first, 1 = second)] */
const RANGE_TABLES: [string, string, number][] = [
  ['PAYLOAD', 'isakmp.nextpayload', 0],
  ['NOTIFY_V1', 'isakmp.notify.msgtype', 0], ['NOTIFY_V2', 'isakmp.notify.msgtype', 1],
  ['ID_TYPE_V1', 'isakmp.id.type', 0], ['ID_TYPE_V2', 'isakmp.id.type', 1],
  ['CERT_V1', 'isakmp.cert.encoding', 0], ['CERT_V2', 'isakmp.cert.encoding', 1],
  ['TRANSFORM_TYPE', 'isakmp.tf.type', 0], ['IKE2_ATTR_TYPE', 'isakmp.ike2.attr.type', 0],
  ['IKE_ATTR_TYPE', 'isakmp.ike.attr.type', 0],
];
const VALUE_TABLES: [string, string, number][] = [
  ['EXCHANGE_TYPE', 'isakmp.exchangetype', 0],
  ['PROTOCOL_V1', 'isakmp.prop.protoid', 0], ['PROTOCOL_V2', 'isakmp.prop.protoid', 1],
  ['ENCR', 'isakmp.tf.id.encr', 0], ['PRF', 'isakmp.tf.id.prf', 0], ['INTEG', 'isakmp.tf.id.integ', 0],
  ['KE_METHOD', 'isakmp.tf.id.dh', 0], ['ESN', 'isakmp.tf.id.esn', 0], ['SA_DOI', 'isakmp.sa.doi', 0],
  ['IKE_ENCRYPTION', 'isakmp.ike.attr.encryption_algorithm', 0], ['IKE_HASH', 'isakmp.ike.attr.hash_algorithm', 0],
  ['IKE_AUTH_METHOD', 'isakmp.ike.attr.authentication_method', 0], ['IKE_GROUP', 'isakmp.ike.attr.group_description', 0],
  ['IKE_GROUP_TYPE', 'isakmp.ike.attr.group_type', 0], ['IKE_LIFE_TYPE', 'isakmp.ike.attr.life_type', 0],
];

let out = `/**
 * ISAKMP's value tables, as the reference names them. GENERATED by
 * \`scripts/parity/gen-isakmp-tables.ts\` from \`tshark -G values\` - edit that,
 * not this. A range table is \`[low, high, name]\` rows, first match wins.
 */
export type RangeTable = readonly (readonly [number, number, string])[];

/** The first row of a range table holding \`value\`, or undefined. */
export function rangeName(table: RangeTable, value: number): string | undefined {
  for (const [low, high, name] of table) if (value >= low && value <= high) return name;
  return undefined;
}
`;
for (const [name, field, which] of RANGE_TABLES) {
  const table = ranges.get(field)?.[which];
  if (table === undefined) throw new Error(`no range table ${which} for ${field}`);
  out += `\nexport const ${name}: RangeTable = [\n${table.map(([lo, hi, n]) => `  [${lo}, ${hi}, ${JSON.stringify(n)}],`).join('\n')}\n];\n`;
}
for (const [name, field, which] of VALUE_TABLES) {
  const table = values.get(field)?.[which];
  if (table === undefined) throw new Error(`no value table ${which} for ${field}`);
  out += `\nexport const ${name}: Readonly<Record<number, string>> = {\n${[...table].map(([v, n]) => `  ${v}: ${JSON.stringify(n)},`).join('\n')}\n};\n`;
}
writeFileSync('src/services/dissectors/isakmpTables.ts', out);
console.log(`wrote ${RANGE_TABLES.length + VALUE_TABLES.length} tables`);
