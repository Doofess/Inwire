/**
 * Writes `src/services/dissectors/rtpEventNames.ts` from the reference's own
 * value table.
 *
 *   npx tsx scripts/parity/gen-rtp-tables.ts
 *
 * An RTP event (RFC 4733) names what a telephone did out of band: a DTMF
 * digit pressed during a call, a fax tone, a line signal. The reference names
 * 183 of them - `DTMF Pound #`, `Fax CNG`, `Cisco NSE: Shift to fax relay
 * mode` - and the Info column prints the name, which is nothing a hand-kept
 * list would get right.
 *
 * The payload types themselves are not here: the reference's table for those
 * is not one `-G values` prints, so `dissectors/rtp.ts` holds it, and
 * `scripts/rtp/dissect.ts` holds every entry of it to the reference.
 *
 * A generator, not a test: it writes a source file and never exits with a
 * status, which is how `check.ts` knows not to run it. Rerun it after a
 * Wireshark upgrade.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

const entries = new Map<number, string>();
for (const line of dump) {
  const cols = line.split('\t');
  if (cols[0] !== 'V' || cols[1] !== 'rtpevent.event_id') continue;
  const value = Number(cols[2]);
  if (!entries.has(value)) entries.set(value, cols[3].trim());
}
if (entries.size === 0) throw new Error('no values for rtpevent.event_id');

const out = `/**
 * RTP event names (RFC 4733) as the reference writes them.
 * GENERATED by \`scripts/parity/gen-rtp-tables.ts\` from \`tshark -G values\` -
 * edit that, not this.
 */

export const RTP_EVENTS: Readonly<Record<number, string>> = {
${[...entries].map(([v, n]) => `  ${v}: ${JSON.stringify(n)},`).join('\n')}
};
`;
writeFileSync('src/services/dissectors/rtpEventNames.ts', out);
console.log(`wrote ${entries.size} event names`);
