/**
 * Writes `src/services/dissectors/sflowNames.ts` from the reference's own
 * value tables.
 *
 *   npx tsx scripts/parity/gen-sflow-tables.ts
 *
 * sFlow names its sample types, its flow and counter record formats, the
 * link type of a sampled header and - for a packet the switch dropped - why it
 * was dropped: some 130 reasons, from ICMP's unreachable codes to Linux's
 * `skb_drop_reason`s, which is what a discarded sample's row prints and
 * nothing a hand-kept list would get right.
 *
 * A generator, not a test: it writes a source file and never exits with a
 * status, which is how `check.ts` knows not to run it. Rerun it after a
 * Wireshark upgrade.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

const TABLES: [string, string][] = [
  ['SAMPLE_TYPES', 'sflow_245.sampletype'],
  ['FLOW_RECORD_FORMATS', 'sflow_245.flow_record_format'],
  ['COUNTER_RECORD_FORMATS', 'sflow_245.counters_record_format'],
  ['HEADER_PROTOCOLS', 'sflow_245.header_protocol'],
  ['IF_DIRECTIONS', 'sflow_245.ifdirection'],
  ['PRECEDENCES', 'sflow_245.ipv4_precedence_type'],
  ['OUTPUT_FORMATS', 'sflow.flow_sample.output_interface_format'],
  ['DISCARD_REASONS', 'sflow.flow_sample.output_interface_value'],
  ['AS_PATH_TYPES', 'sflow.as_type'],
];

let out = `/**
 * sFlow's names as the reference writes them. GENERATED by
 * \`scripts/parity/gen-sflow-tables.ts\` from \`tshark -G values\` - edit
 * that, not this.
 */
`;
for (const [name, field] of TABLES) {
  const entries = new Map<number, string>();
  for (const line of dump) {
    const cols = line.split('\t');
    if (cols[0] !== 'V' || cols[1] !== field) continue;
    const value = Number(cols[2]);
    if (!entries.has(value)) entries.set(value, cols[3].trim());
  }
  if (entries.size === 0) throw new Error(`no values for ${field}`);
  out += `\nexport const ${name}: Readonly<Record<number, string>> = {\n${[...entries].sort((a, b) => a[0] - b[0])
    .map(([v, n]) => `  ${v}: ${JSON.stringify(n)},`).join('\n')}\n};\n`;
}
writeFileSync('src/services/dissectors/sflowNames.ts', out);
console.log(`wrote ${TABLES.length} tables`);
