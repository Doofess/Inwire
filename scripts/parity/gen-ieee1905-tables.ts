/**
 * Writes `src/services/dissectors/ieee1905Names.ts` from the reference's own
 * value tables.
 *
 *   npx tsx scripts/parity/gen-ieee1905-tables.ts
 *
 * IEEE 1905.1a and the Wi-Fi Alliance's EasyMesh on top of it name some 80
 * message types and 133 TLV types, and a mesh from a vendor other than the
 * one this repository's fixture was captured behind sends ones a hand-kept
 * list did not have - which read as "Unknown TLV" on a laptop overhearing
 * somebody else's mesh. The hand-kept list had also swapped types 6 and 7.
 *
 * A generator, not a test: it writes a source file and never exits with a
 * status, which is how `check.ts` knows not to run it. Rerun it after a
 * Wireshark upgrade.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { findWiresharkTool } from '../export/realCaptures';

const tshark = findWiresharkTool('tshark');
if (tshark === null) throw new Error('tshark not found');
const dump = spawnSync(tshark, ['-G', 'values'], { encoding: 'utf8', maxBuffer: 1 << 28 }).stdout.split(/\r?\n/);

const TABLES: [string, string, number][] = [
  ['MESSAGE_TYPES', 'ieee1905.message_type', 4],
  ['TLV_TYPES', 'ieee1905.tlv_type', 2],
];

let out = `/**
 * IEEE 1905.1a / EasyMesh message and TLV names as the reference writes them.
 * GENERATED by \`scripts/parity/gen-ieee1905-tables.ts\` from \`tshark -G
 * values\` - edit that, not this.
 */
`;
for (const [name, field, digits] of TABLES) {
  const entries = new Map<number, string>();
  for (const line of dump) {
    const cols = line.split('\t');
    if (cols[0] !== 'V' || cols[1] !== field) continue;
    const value = Number(cols[2]);
    if (!entries.has(value)) entries.set(value, cols[3].trim());
  }
  if (entries.size === 0) throw new Error(`no values for ${field}`);
  out += `\nexport const ${name}: Readonly<Record<number, string>> = {\n${[...entries]
    .map(([v, n]) => `  0x${v.toString(16).padStart(digits, '0')}: ${JSON.stringify(n)},`).join('\n')}\n};\n`;
}
writeFileSync('src/services/dissectors/ieee1905Names.ts', out);
console.log(`wrote ${TABLES.length} tables`);
