for (const [hex, expected] of CASES) {
  const raw = bytes(hex);
  const { packet } = decodeRawEthernetPacket(raw, 1, Date.now(), 0, 0, raw.length);
  check(`info: ${expected.slice(0, 58)}`, packet.info, expected);
}

// The Protocol column and the layer must both be right, not just the Info.
const oneRaw = bytes(CASES[0][0]);
const { packet: one } = decodeRawEthernetPacket(oneRaw, 1, Date.now(), 0, 0, oneRaw.length);
check('protocol label is LLDP', one.protocolLabel, 'LLDP');
check(
  'a Link Layer Discovery Protocol layer is present',
  one.layers.some((l) => l.name === 'Link Layer Discovery Protocol'),
  true,
);
// Frame 1's TLVs: Chassis Id 14..19, Port Id 20..25, TTL 26..29, End 30..31.
// The frame is padded to the 60-byte Ethernet minimum, so bytes 32..59 are
// padding that reads as a run of type-0 TLVs - the layer must stop at 31.
check(
  'the LLDPDU layer ends at the End TLV, excluding Ethernet padding',
  one.layers.find((l) => l.name === 'Link Layer Discovery Protocol')?.rawBytesRange?.[1],
  31,
);
check('chassis id is published as a filter field', one.fields?.['lldp.chassis.id'], 'CID');
check('ttl is published as a filter field', one.fields?.['lldp.time_to_live'], 77);

// Reserved group destinations. 0x...0e and 0x...03 were swapped in
// RESERVED_MAC_NAMES, so every LLDP frame named the wrong bridge group; these
// two names come from `tshark -e eth.dst_resolved` for these exact frames.
const named = (hex: string) => {
  const raw = bytes(hex);
  return decodeRawEthernetPacket(raw, 1, Date.now(), 0, 0, raw.length).packet.destination;
};
check('01:80:c2:00:00:0e resolves to Nearest-Bridge', named(CASES[49][0]), 'Nearest-Bridge');
check('01:80:c2:00:00:03 resolves to Nearest-non-TPMR-Bridge', named(CASES[51][0]), 'Nearest-non-TPMR-Bridge');

// A truncated LLDPDU must still decode what it can rather than throwing.
const truncRaw = bytes(CASES[0][0].slice(0, 44));
const { packet: truncated } = decodeRawEthernetPacket(truncRaw, 1, Date.now(), 0, 0, truncRaw.length);
check('a truncated LLDPDU still reports LLDP', truncated.protocolLabel, 'LLDP');
check('a truncated LLDPDU never shows the frame-length placeholder',
  /^Frame \(/.test(truncated.info), false);

console.log(failures === 0 ? '\nAll checks passed.' : `\n${failures} check(s) FAILED.`);
process.exit(failures === 0 ? 0 : 1);
