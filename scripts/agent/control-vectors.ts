/**
 * The Rust agent's control messages, against the app's own parser.
 *
 *   npx tsx scripts/agent/control-vectors.ts
 *
 * ## Why this exists rather than a Rust-side assertion
 *
 * `parseAgentMessage` **returns null for anything it does not recognise**, and
 * that is correct: the agent is the one thing on the machine allowed to send
 * this app messages, and a validator that guessed would be a validator that
 * accepted a malformed one.
 *
 * It also means a wrong shape from the agent does not fail loudly. It is
 * dropped by a function doing its job, and the symptom is an app that connects
 * and then shows nothing - no error, no log line, no clue. That is the failure
 * this file is here to make impossible.
 *
 * The fixture is generated by the Rust agent itself:
 *
 *   cargo run --manifest-path agent-rs/Cargo.toml --example control_vectors \
 *     > scripts/agent/control-vectors.json
 *
 * so `npm run check` covers the Rust agent's output **without cargo being
 * installed** - which matters because CI is ubuntu and the whole promise of
 * `scripts/` is plain tsx with no toolchain.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  parseAgentMessage,
  summarizeCaptureStats,
  type AgentCaptureStatsMessage,
} from '../../src/services/agentProtocol';

let failures = 0;
function check(name: string, actual: unknown, expected: unknown): void {
  const pass = JSON.stringify(actual) === JSON.stringify(expected);
  if (!pass) failures++;
  console.log(`${pass ? 'PASS' : 'FAIL'}  ${name}`);
  if (!pass) {
    console.log(`        expected ${JSON.stringify(expected)}`);
    console.log(`        actual   ${JSON.stringify(actual)}`);
  }
}

interface Fixture {
  cases: { note: string; message: Record<string, unknown> }[];
}

const fixture: Fixture = JSON.parse(
  readFileSync(join(import.meta.dirname, 'control-vectors.json'), 'utf8'),
);

console.log('--- every message the Rust agent sends is one this app accepts ---');
console.log();

for (const { note, message } of fixture.cases) {
  const parsed = parseAgentMessage(JSON.stringify(message));
  check(note, parsed === null ? 'REJECTED BY THE PARSER' : parsed.type, message.type);
}

console.log();
console.log('--- and the ones carrying numbers mean what the app reads them as ---');
console.log();

{
  // Picking the cases out by shape rather than by index, so re-ordering the
  // fixture cannot silently point these at a different message.
  const stats = fixture.cases
    .map((c) => c.message)
    .filter((m) => m.type === 'capture_stats');
  check('the fixture carries capture_stats cases at all', stats.length > 0, true);

  const readable = stats.find((m) =>
    (m.interfaces as { droppedKernel: number | null }[]).every((i) => i.droppedKernel !== null));
  const unreadable = stats.find((m) =>
    (m.interfaces as { droppedKernel: number | null }[]).some((i) => i.droppedKernel === null));
  const noPipe = stats.find((m) => m.droppedPipe === undefined);

  if (readable) {
    const s = summarizeCaptureStats(
      parseAgentMessage(JSON.stringify(readable)) as AgentCaptureStatsMessage,
    );
    check('every counter readable sums to a number', typeof s.droppedKernel, 'number');
  }
  if (unreadable) {
    const s = summarizeCaptureStats(
      parseAgentMessage(JSON.stringify(unreadable)) as AgentCaptureStatsMessage,
    );
    // The rule with a post-mortem behind it: one unreadable interface makes the
    // SUM unknown rather than an undercount, because adding the rest would
    // report a confident number that is too low.
    check('one unreadable interface makes the whole sum unknown', s.droppedKernel, null);
  }
  if (noPipe) {
    const s = summarizeCaptureStats(
      parseAgentMessage(JSON.stringify(noPipe)) as AgentCaptureStatsMessage,
    );
    check('an omitted pipe counter reads as unknown, not as none', s.droppedPipe, null);
  } else {
    check('the fixture carries a message with no droppedPipe', false, true);
  }
}

{
  // `hello` is the one message whose absence has no fallback: the app waits for
  // it, and an agent that never sends a recognisable one reads as incompatible.
  const hellos = fixture.cases.map((c) => c.message).filter((m) => m.type === 'hello');
  check('every hello parses', hellos.every((h) => parseAgentMessage(JSON.stringify(h)) !== null), true);
  check('...and none of them asks for a pairing token',
    hellos.every((h) => h.authRequired === false), true);
  // A machine with no Npcap has no interfaces, and that must still be a valid
  // hello - it is the state a fresh install lands in.
  check('...including one with no interfaces at all',
    hellos.some((h) => Array.isArray(h.interfaces) && h.interfaces.length === 0), true);
}

console.log();
if (failures) {
  console.log(`${failures} control vector check(s) FAILED`);
  console.log('If the Rust agent\'s shapes changed on purpose, regenerate with');
  console.log('  cargo run --manifest-path agent-rs/Cargo.toml --example control_vectors \\');
  console.log('    > scripts/agent/control-vectors.json');
  process.exit(1);
}
console.log('All control vector checks passed.');
process.exit(0);
