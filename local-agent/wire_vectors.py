"""The wire format's golden vectors, in one file three languages read.

There are three implementations of this format - Python here, TypeScript in
`src/services/agentBinary.ts` and `src/services/agentFraming.ts`, and Rust in
`agent-rs/` - and until now the first two were held together by each asserting
its own hand-written copy of the same bytes. That works right up until somebody
edits one copy, and then it reports that both sides agree with themselves.

So the bytes live in `scripts/agent/wire-vectors.json`, once, and every
implementation is checked against that file rather than against its own idea of
it. A new implementation joins by reading the same file; it does not get to
bring its own vectors.

    python local-agent/wire_vectors.py --check     # the default
    python local-agent/wire_vectors.py --write     # regenerate from Python

`--write` is deliberately a separate verb. Regenerating on every run would mean
a change to the encoder silently rewrote the thing that was supposed to catch
it, which is the same shape as a test that asserts the code against itself.
"""
import argparse
import base64
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import packet_batch
import pipe_frame

FIXTURE = (pathlib.Path(__file__).resolve().parent.parent
           / "scripts" / "agent" / "wire-vectors.json")

#: Inputs chosen to pin the edges, not the middle.
#:
#: - a full-size frame with an ordinary sequence number and a timestamp in
#:   Npcap's 100 ns steps
#: - `seq` at the u32 ceiling, an empty payload, and a timestamp whose last
#:   digit is a single nanosecond - past 2^53, so a decoder that goes through a
#:   float gets it wrong, which is the failure version 3 exists to prevent
#: - a 9,000-byte jumbo, whose lengths need more than a byte each
#: - the last nanosecond whose microsecond count a double still holds exactly
#:   (2^53 - 1 of them, then 999 ns): the app decodes a stamp as whole
#:   microseconds plus a remainder without a BigInt, which is exact up to
#:   here - the year 2255 - and a decoder that took a shortcut is not
#:
#: `tsNs` is written into the file as a decimal STRING: JSON numbers past 2^53
#: are rounded by TypeScript's `JSON.parse` before any decoder sees them.
RECORDS = [
    {"seq": 0, "iface": 0, "tsNs": 1788477971653284300, "origLen": 1514,
     "data": bytes(range(64))},
    {"seq": 4294967295, "iface": 7, "tsNs": 1788477971653285501, "origLen": 60,
     "data": b""},
    {"seq": 9, "iface": 1, "tsNs": 1000, "origLen": 9000, "data": b"\xff" * 9000},
    # A truncated frame: captured at 128 bytes of a 200,000-byte send - a wire
    # length no 16-bit field holds, so a decoder still reading version 3's
    # layout, or truncating origLen to 16 bits, gets it wrong.
    {"seq": 12345, "iface": 2, "tsNs": 9007199254740991999, "origLen": 200000,
     "data": b"\xab" * 128},
]

#: Control messages, for the framing layer.
FRAMES = [
    {"kind": "json", "text": '{"type":"refresh_adapters"}'},
    {"kind": "json", "text": "{}"},
    {"kind": "binary", "data": b""},
    {"kind": "binary", "data": bytes(range(256))},
]


def build() -> dict:
    records = []
    for r in RECORDS:
        encoded = packet_batch.encode_record(
            r["seq"], r["iface"], r["tsNs"], r["origLen"], r["data"])
        records.append({
            "seq": r["seq"], "iface": r["iface"], "tsNs": str(r["tsNs"]),
            "origLen": r["origLen"],
            "dataBase64": base64.b64encode(r["data"]).decode("ascii"),
            "encodedHex": encoded.hex(),
        })

    batch = packet_batch.encode_batch([
        packet_batch.encode_record(r["seq"], r["iface"], r["tsNs"], r["origLen"], r["data"])
        for r in RECORDS
    ])

    frames = []
    for f in FRAMES:
        if f["kind"] == "json":
            encoded = pipe_frame.encode_frame(
                pipe_frame.FRAME_JSON, f["text"].encode("utf-8"))
            frames.append({"kind": "json", "text": f["text"],
                           "encodedHex": encoded.hex()})
        else:
            encoded = pipe_frame.encode_frame(pipe_frame.FRAME_BINARY, f["data"])
            frames.append({"kind": "binary",
                           "dataBase64": base64.b64encode(f["data"]).decode("ascii"),
                           "encodedHex": encoded.hex()})

    return {
        "note": ("Golden bytes for Inwire's agent wire format. Generated by "
                 "local-agent/wire_vectors.py --write. Every implementation is "
                 "checked against THIS file rather than its own copy."),
        "constants": {
            "recordBytes": packet_batch.RECORD.size,
            "headerBytes": packet_batch.HEADER.size,
            "magic": packet_batch.MAGIC.decode("ascii"),
            "version": packet_batch.VERSION,
            "frameJson": pipe_frame.FRAME_JSON,
            "frameBinary": pipe_frame.FRAME_BINARY,
            "maxFrameBytes": pipe_frame.MAX_FRAME_BYTES,
        },
        "records": records,
        "batchHex": batch.hex(),
        "frames": frames,
    }


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--write", action="store_true",
                   help="regenerate the fixture from this implementation")
    args = p.parse_args()

    built = build()
    if args.write:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(built, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {FIXTURE}")
        return 0

    if not FIXTURE.exists():
        print(f"FAIL  {FIXTURE} does not exist - run with --write")
        return 1
    stored = json.loads(FIXTURE.read_text(encoding="utf-8"))
    failures = 0
    for key in ("constants", "records", "batchHex", "frames"):
        if stored.get(key) != built.get(key):
            print(f"FAIL  {key} does not match this implementation")
            failures += 1
        else:
            print(f"PASS  {key} matches")
    if failures:
        print("\nThe Python encoder and the golden vectors disagree. If the "
              "change was intended, regenerate with --write and update the "
              "Rust and TypeScript sides in the same commit.")
        return 1
    print("\nPython agrees with the golden vectors.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
